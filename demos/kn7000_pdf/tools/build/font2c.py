# font2c.py FONT8X13_INC OUT_C -- the KN7000 loader's 8x13 text font (technics-roms-disasm
# kn7000/tools/cnv_romdump/font8x13.inc, from the X11 misc-fixed 8x13 font, public domain) as a C array for
# KN7APP.BIN: `const unsigned char font8x13[95][13]`, characters 0x20-0x7E, top row first, bit 7 leftmost.
import re
import sys

src, out = sys.argv[1:3]
glyphs = []
for line in open(src):
    m = re.match(r'\s*\.byte\s+(.*?)\s*(#.*)?$', line)
    if m:
        glyphs.append([int(v, 0) for v in m.group(1).split(',')])
assert len(glyphs) == 95 and all(len(g) == 13 for g in glyphs), 'not the 95 glyphs of 13 rows expected'
with open(out, 'w') as f:
    f.write('/* generated by tools/build/font2c.py from the loader\'s font8x13.inc (X11 misc-fixed 8x13, public domain) */\n')
    f.write('const unsigned char font8x13[95][13] = {\n')
    for g in glyphs:
        f.write('    {' + ', '.join(f'0x{v:02x}' for v in g) + '},\n')
    f.write('};\n')
