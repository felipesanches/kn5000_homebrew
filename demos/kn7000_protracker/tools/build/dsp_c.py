# dsp_c.py AW_TOOLS OUT.h UNIDASM -- the effects DSP's sample mixer for KN7APP.BIN (src/app/dsp.c), as a C header.
# The mixer is Another World's, unchanged: technics-anotherworld kn7000/tools/dsp_mixer.py (an eight-voice mixer
# hooked into two of the firmware kernel's unit slots, which played on the owner's KN7000 on 2026-10-21), imported
# from AW_TOOLS. Every PM word is first disassembled with MAME's unidasm and compared with the text it was meant to
# be, as that repository's build does: any difference stops the build. Writes the program as 16-bit halves (least
# significant first, as the host streams them), the variables, and the addresses dsp.c needs.
import os
import sys

aw_tools, out, unidasm = sys.argv[1:4]
sys.path.insert(0, aw_tools)
import dsp_mixer as m  # noqa: E402

words, labels = m.program()
assert m.PM_CODE + len(words) <= m.PM_END
if not os.path.exists(unidasm):
    sys.exit(f"dsp_c: no unidasm at {unidasm}: every word of the mixer must be checked against it")
bad = m.check(words, unidasm)
if bad:
    sys.exit(f"dsp_c: {bad} instruction(s) of the mixer do not disassemble as meant")
eq = [("DSP_CODE_ADDR", m.PM_CODE), ("DSP_CODE_WORDS", len(words)), ("DSP_ENTRY0", labels["E0"]),
      ("DSP_ENTRY9", labels["E9"]), ("DSP_OURS_LO", 0x8100), ("DSP_OURS_HI", m.PM_END), ("DSP_SLOT0", m.PM_SLOT0),
      ("DSP_SLOT9", m.PM_SLOT9), ("DSP_DEF0", m.DEF_TARGET0), ("DSP_DEF9", m.DEF_TARGET9),
      ("DSP_CALLDB_HI", m.CALL_DB >> 32), ("DSP_MARK", m.MARK), ("DSP_VARS", m.VARS), ("DSP_NVARS", m.VARS_END - m.VARS),
      ("DSP_V_MIX", m.V_MIX), ("DSP_VOICES", m.VOICES), ("DSP_VOICE_LEN", m.VOICE_LEN), ("DSP_CMDS", m.CMDS),
      ("DSP_CMD_LEN", m.CMD_LEN), ("DSP_NVOICES", m.NVOICES), ("DSP_STAGE", m.STAGE), ("DSP_STAGE_HALF", m.STAGE_HALF),
      ("DSP_COPY_STEP", m.COPY_STEP), ("DSP_BANK", m.BANK), ("DSP_BANK_MAX", m.BANK_MAX), ("DSP_MSGR4", m.MSGR4),
      ("DSP_MSGR5", m.MSGR5), ("DSP_MSGR6", m.MSGR6), ("DSP_MSGR7", m.MSGR7)]
with open(out, "w") as f:
    f.write("/* GENERATED by tools/build/dsp_c.py from technics-anotherworld kn7000/tools/dsp_mixer.py: do not edit */\n")
    f.write("#ifndef PF_DSP_MIXER_H\n#define PF_DSP_MIXER_H\n")
    for name, val in eq:
        f.write(f"#define {name} 0x{val:X}u\n")
    f.write("static const u16 dsp_code[] = {\n")
    for pc, w, text in words:
        f.write(f"    0x{w & 0xFFFF:04X}, 0x{(w >> 16) & 0xFFFF:04X}, 0x{w >> 32:04X},  /* {pc:04X}: {text} */\n")
    f.write("};\nstatic const u32 dsp_vars[] = {\n")
    v = m.dsp_vars()
    for k in range(0, len(v), 8):
        f.write("    " + ", ".join(f"0x{x:08X}" for x in v[k:k + 8]) + ",\n")
    f.write("};\n#endif\n")
print(f"dsp_c: {out}: {len(words)} PM words at 0x{m.PM_CODE:04X}, each disassembles as meant (unidasm -arch sharc)")
